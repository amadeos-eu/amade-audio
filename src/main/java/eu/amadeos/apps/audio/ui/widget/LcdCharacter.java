    private final char ch;
    private final byte[] cols;

    // --8<-- [start:rows]
    LcdCharacter(char ch, String... rows) {
        this.ch = ch;
        this.cols = new byte[5];
        for (int r = 0; r < Math.min(rows.length, 7); r++) {
            String row = rows[r];
            for (int c = 0; c < Math.min(row.length(), 5); c++) {
                char dot = row.charAt(c);
                if (dot == 'X' || dot == 'O' || dot == '#' || dot == 'x') {
                    this.cols[c] |= (byte) (1 << r);
                }
            }
        }
    }
    // --8<-- [end:rows]

    char character() {
        return ch;
    }

    byte[] columns() {
        return cols;
    }
